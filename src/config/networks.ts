const BY_ID = new Map<string, NetworkEntry>(ALL_NETWORKS.map((n) => [n.id, n]))
const BY_EVM_ID = new Map<number, NetworkEntry>(EVM_NETWORKS.map((n) => [n.evmChainId!, n]))

export function getNetwork(id?: string | null): NetworkEntry | undefined {
  return id ? BY_ID.get(id) : undefined
}

export function findNetworkByEvmId(chainId?: number | null): NetworkEntry | undefined {
  return chainId != null ? BY_EVM_ID.get(chainId) : undefined
}

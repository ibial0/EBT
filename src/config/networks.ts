/**
 * Centralized, multi-family network registry — single source of truth for EVM,
 * Non-EVM, verified aliases, and explicitly deprecated historical testnets.
 */
import { CHAINS, type ChainCfg, type FaucetLink } from './chains'
import { chainLogoFile, nonEvmLogoFile } from './logos'
import type { NonEvmFamily, WalletFamily } from '../lib/walletsMulti'

export type NetworkFamily = 'evm' | NonEvmFamily

export type NetworkStatus = 'existing' | 'active' | 'deprecated'

export type CapabilityLevel = 'yes' | 'partial' | 'no'

export interface NetworkCapabilities {
  rpc: boolean
  wallet: CapabilityLevel
  portfolio: CapabilityLevel
  swap: CapabilityLevel
  bridge: CapabilityLevel
  faucet: CapabilityLevel
}

export interface NetworkEntry {
  /** canonical CAIP-style or namespace id, never just display name */
  id: string
  key: string
  name: string
  short: string
  aliases: string[]
  generation: string
  family: NetworkFamily
  walletFamily: WalletFamily
  /** present on EVM chains in src/config/chains.ts */
  evmChainId?: number
  /** optional EVM sidecar metadata when a non-EVM chain also exposes an EVM endpoint */
  evmSidecar?: { chainId: number; rpcUrl: string; explorerUrl: string; symbol: string }
  nativeId: string
  status: NetworkStatus
  statusNote?: string
  docsUrl: string
  metadataSource: string
  rpcUrl: string
  explorerUrl: string
  nativeCurrency: { symbol: string; name: string; decimals: number }
  logoFile?: string
  color: string
  gradient: [string, string]
  faucets: FaucetLink[]
  capabilities: NetworkCapabilities
  verifiedAt: string
}


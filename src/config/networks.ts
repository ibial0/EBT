function fromEvmChain(c: ChainCfg): NetworkEntry {
  const isExisting = EXISTING_IDS.has(c.id)
  const hasSwap = Boolean(c.uniswap || c.dexV2?.length)
  const hasBridge = c.bridge !== 'none' || Boolean(c.cctpDomain != null && c.usdc) || c.opStackParent != null
  const activeFaucets = c.faucets.filter((f) => !f.missing && !f.inactive)

  return {
    id: `eip155:${c.id}`,
    key: c.key,
    name: c.name,
    short: c.short,
    aliases: ALIASES_BY_EVM_ID[c.id] ?? [],
    generation: c.name.includes('Sepolia')
      ? 'Sepolia-anchored testnet'
      : c.name.includes('Hoodi')
        ? 'Hoodi-anchored testnet'
        : 'Current active testnet',
    family: 'evm',
    walletFamily: 'evm',
    evmChainId: c.id,
    nativeId: String(c.id),
    status: isExisting ? 'existing' : 'active',
    docsUrl: c.viem.blockExplorers?.default?.url ?? '',
    metadataSource: isExisting ? 'Preserved baseline + on-chain RPC' : 'Chainlink Faucet / Circle Docs / viem + live CORS RPC',
    rpcUrl: c.viem.rpcUrls.default.http[0],
    explorerUrl: c.viem.blockExplorers?.default?.url ?? '',
    nativeCurrency: {
      symbol: c.nativeIsUsdc ? 'USDC' : c.viem.nativeCurrency.symbol,
      name: c.viem.nativeCurrency.name,
      decimals: c.viem.nativeCurrency.decimals,
    },
    logoFile: chainLogoFile(c.key, c.id),
    color: c.color,
    gradient: c.gradient,
    faucets: c.faucets,
    capabilities: {
      rpc: true,
      wallet: 'yes',
      portfolio: 'yes',
      swap: hasSwap ? 'yes' : 'no',
      bridge: hasBridge ? 'yes' : 'no',
      faucet: activeFaucets.length > 0 ? 'yes' : 'no',
    },
    verifiedAt: c.verifiedAt,
  }
}

